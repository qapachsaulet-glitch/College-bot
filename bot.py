def main():

    if TOKEN == "ВСТАВЬ_СЮДА_ТОКЕН_БОТА":
        print("ОШИБКА: Вставь токен Telegram-бота!")
        return

    app = (
        Application.builder()
        .token(TOKEN)
        .build()
    )

    app.add_handler(
        CommandHandler("start", start)
    )

    app.add_handler(
        CommandHandler("help", help_command)
    )

    app.add_handler(
        CommandHandler("menu", menu_command)
    )

    app.add_handler(
        CallbackQueryHandler(buttons)
    )

    print("================================")
    print("COLLEGE ASSISTANT ЗАПУЩЕН!")
    print("Қарағанды жоғары гуманитарлық колледжі")
    print("================================")

    app.run_pollin
