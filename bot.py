# ОБРАБОТКА КНОПОК
# ==========================================

async def buttons(
    update: Update,
    context: ContextTypes.DEFAULT_TYPE
):

    query = update.callback_query

    await query.answer()

    data = query.data

    if data == "home":

        await query.edit_message_text(
            "🏠 ГЛАВНОЕ МЕНЮ\n\nВыбери нужный раздел:",
            reply_markup=main_keyboard()
        )

    elif data == "applicant":

        await query.edit_message_text(
            """
🎓 АБИТУРИЕНТУ

Добро пожаловать!

Этот раздел поможет тебе
подготовиться к поступлению
в наш колледж.

Выбери интересующую тему:
""",
            reply_markup=applicant_keyboard()
        )

    elif data == "student":

        await query.edit_message_text(
            """
📚 СТУДЕНТАМ

Добро пожаловать!

Здесь собрана полезная
информация для студентов.
""",
            reply_markup=student_keyboard()
        )

    elif data == "social":

        await query.edit_message_text(
            INFO["social"],
            reply_markup=social_keyboard()
        )

    elif data in INFO:

        await query.edit_message_text(
            INFO[data],
            reply_markup=back_keyboard()
        )


